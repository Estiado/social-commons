"""Derive the homepage alpha and interaction edge from the same real-photo trace."""
from pathlib import Path
import json
import sys
from PIL import Image, ImageDraw, ImageFilter


def build_boundary(root: Path):
    trace = json.loads((root / 'design/type-study/source/home-wall-trace.json').read_text(encoding='utf-8'))
    cfg = trace['transform']
    width, height = cfg['size']
    # Correct perspective and amplify only the measured masonry relief; no invented crenels.
    points = []
    for x, y in trace['profile']:
        t = (x - cfg['sourceX']) / cfg['sourceWidth']
        points.append((width * t, cfg['offsetY'] + (y - (cfg['baselineY'] - cfg['baselineSlope'] * t)) * cfg['relief'] + cfg['layoutSlope'] * t))
    silhouette = Image.new('L', (width, height))
    ImageDraw.Draw(silhouette).polygon(points + [(width, height), (0, height)], fill=255)
    silhouette = silhouette.filter(ImageFilter.GaussianBlur(cfg['feather']))
    # Derive each column from the rasterized outline, including real overhangs.
    hard = Image.new('L', (width, height))
    ImageDraw.Draw(hard).polygon(points + [(width, height), (0, height)], fill=255)
    mask_pixels = silhouette.load()
    hard_pixels = hard.load()
    edge = []
    for x in range(width):
        top = next((y for y in range(height) if hard_pixels[x, y]), height - 1)
        edge.append(top / height)
        for y in range(height):
            depth = max(0, min(1, (y - top) / cfg['fadeDepth']))
            smooth = depth * depth * (3 - 2 * depth)
            mask_pixels[x, y] = round(mask_pixels[x, y] * (cfg['edgeOpacity'] + (1 - cfg['edgeOpacity']) * smooth))
    rgba = Image.new('RGBA', silhouette.size, 'white')
    rgba.putalpha(silhouette)
    rgba.save(root / 'public/type-study/materials/type-field-wall-mask.png')
    # Sample every pixel so hit testing agrees with alpha, including the narrow battlement notches.
    values = ','.join(str(round(v, 4)) for v in edge)
    source = '''/** Generated by scripts/type_boundary.py from the real Jinshanling photo trace. */
const edge = [''' + values + '''];
export function boundaryAt(x: number): number {
  const u = Math.max(0, Math.min(1, x)) * (edge.length - 1);
  const a = Math.floor(u), b = Math.min(edge.length - 1, a + 1);
  return edge[a] + (edge[b] - edge[a]) * (u - a);
}
'''
    (root / 'src/features/book/typeBoundary.ts').write_text(source, encoding='utf-8')
    print('Built photo-traced wall alpha and matching interaction boundary:', cfg)


if __name__ == '__main__':
    build_boundary(Path(sys.argv[1]))
