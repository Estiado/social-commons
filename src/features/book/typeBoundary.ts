export function boundaryAt(x: number): number {
  const u = Math.max(0, Math.min(1, x));
  for (let i = 1; i < points.length; i++) {
    if (u <= points[i][0]) {
      const a = points[i - 1],
        b = points[i];
      return a[1] + ((b[1] - a[1]) * (u - a[0])) / (b[0] - a[0]);
    }
  }
  return points.at(-1)![1];
}
