这番话不免噜嗦，但是我们原在咬文嚼字，非这样锱铢必较不可。咬文嚼字有时是一个坏习惯，所以这个成语的涵义通常不很好。但是在文学，无论阅读或写作，我们必须有一字不肯放松的谨严。文学借文字表现思想情感；文字上面有含糊，就显得思想还没有透彻，情感还没有凝炼。咬文嚼字，在表面上像只是斟酌文字的分量，在实际上就是调整思想和情感。从来没有一句话换一个说法而意味仍完全不变。

